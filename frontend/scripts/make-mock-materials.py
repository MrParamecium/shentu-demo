"""生成网申模拟用的示例材料 PDF（虚构申请人，带 SAMPLE 水印）。

用法：python3 frontend/scripts/make-mock-materials.py
输出：frontend/public/mock-materials/*.pdf
依赖：reportlab（pip install reportlab）

所有人名、学校、成绩、编号都是虚构的，只用于在申途的模拟网申里练习上传。
语言成绩单故意不仿照任何考试机构的官方版式。
"""

from pathlib import Path

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas

OUT = Path(__file__).resolve().parent.parent / "public" / "mock-materials"
W, H = A4
APPLICANT = "Ming LI"
SCHOOL = "Example University of Technology (fictional)"


def watermark(c: canvas.Canvas) -> None:
    c.saveState()
    c.setFillColorRGB(0.85, 0.2, 0.2, alpha=0.12)
    c.setFont("Helvetica-Bold", 40)
    c.translate(W / 2, H / 2)
    c.rotate(35)
    c.drawCentredString(0, 0, "SAMPLE - SIMULATION ONLY")
    c.restoreState()
    c.setFont("Helvetica", 8)
    c.setFillColorRGB(0.5, 0.5, 0.5)
    c.drawCentredString(W / 2, 12 * mm, "Fictional sample generated by Shentu demo. Not a real document. Do not submit to any institution.")
    c.setFillColorRGB(0, 0, 0)


def lines(c: canvas.Canvas, x: float, y: float, rows: list[str], size: int = 10, lead: float = 14) -> float:
    c.setFont("Helvetica", size)
    for r in rows:
        c.drawString(x, y, r)
        y -= lead
    return y


def heading(c: canvas.Canvas, x: float, y: float, text: str, size: int = 12) -> float:
    c.setFont("Helvetica-Bold", size)
    c.drawString(x, y, text)
    return y - size - 6


def new(name: str) -> canvas.Canvas:
    c = canvas.Canvas(str(OUT / name), pagesize=A4)
    c.setTitle(f"{name} (sample)")
    c.setAuthor("Shentu demo - fictional sample")
    return c


def cv() -> None:
    c = new("sample-cv.pdf")
    x, y = 20 * mm, H - 25 * mm
    c.setFont("Helvetica-Bold", 18)
    c.drawString(x, y, APPLICANT)
    y = lines(c, x, y - 18, ["Email: ming.li@example.com  |  Phone: +86 000 0000 0000 (fictional)"], 9)
    y = heading(c, x, y - 10, "EDUCATION")
    y = lines(c, x, y, [
        f"{SCHOOL}                                   Sep 2023 - Jun 2027 (expected)",
        "BSc in Information Management and Information Systems   |   GPA 3.6 / 4.0 (sample)",
        "Core courses: Statistics, Database Systems, Data Mining, Operations Research",
    ])
    y = heading(c, x, y - 10, "EXPERIENCE")
    y = lines(c, x, y, [
        "Data Analyst Intern, Example Retail Co. (fictional)            Jul 2026 - Sep 2026",
        "- Built weekly sales dashboard in SQL and Tableau for 30 stores",
        "- Forecast demand with time-series models; reduced stock-outs by 8% in pilot",
        "",
        "Research Assistant, School of Management (fictional)           Mar 2025 - Jun 2026",
        "- Cleaned 200k-row survey dataset in Python (pandas)",
        "- Co-wrote a course report on customer churn prediction",
    ])
    y = heading(c, x, y - 10, "SKILLS")
    lines(c, x, y, ["Python, SQL, R, Tableau, Excel  |  English (IELTS 7.0, sample)  |  Mandarin (native)"])
    watermark(c)
    c.save()


