def transcript() -> None:
    c = new("sample-transcript.pdf")
    x, y = 20 * mm, H - 25 * mm
    y = heading(c, x, y, f"{SCHOOL}", 14)
    y = lines(c, x, y, [
        "Academic Transcript (sample)",
        f"Student: {APPLICANT}   |   Student No.: 2023000000 (fictional)",
        "Programme: BSc Information Management and Information Systems",
    ])
    y -= 8
    rows = [
        ("Course", "Credits", "Grade"),
        ("Calculus", "4", "88"), ("Linear Algebra", "3", "85"),
        ("Probability and Statistics", "4", "90"), ("Database Systems", "3", "92"),
        ("Data Mining", "3", "87"), ("Operations Research", "3", "84"),
        ("Programming in Python", "3", "93"), ("Microeconomics", "3", "82"),
    ]
    c.setFont("Helvetica", 10)
    for i, (a, b, g) in enumerate(rows):
        if i == 0:
            c.setFont("Helvetica-Bold", 10)
        c.drawString(x, y, a)
        c.drawString(x + 110 * mm, y, b)
        c.drawString(x + 140 * mm, y, g)
        c.setFont("Helvetica", 10)
        y -= 15
    lines(c, x, y - 10, ["Cumulative GPA: 3.6 / 4.0 (sample)", "Issued for simulation only."])
    watermark(c)
    c.save()


